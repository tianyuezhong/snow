export const states = ["未尝试", "练习中", "偶尔完成", "稳定完成"];
export function matchCards(ids: string[]) {
  const matched = cards.filter((c) => ids.includes(c.skillId));
  if (matched.length === 1) {
    const c = matched[0];
    return [
      c,
      {
        ...c,
        id: c.id + "-review",
        title: c.title.split(" · ")[0] + " · 现场准备复核",
        purpose: "再次核对能力、场地与停止条件。",
      },
    ];
  }
  return matched.slice(0, 3);
}
